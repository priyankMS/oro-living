/** A product is "coming soon" until at least one real photo has been added. */
export function isComingSoon(product: Product) {
  return !product.images.some((image) => image.src);
}

export function getProductBySlug(slug: string) {
  return PRODUCTS.find((product) => product.slug === slug);
}

export function getProductsBySpace(spaceSlug: string) {
  return PRODUCTS.filter((product) => product.spaces.includes(spaceSlug));
}

export function getProductsByCollection(collectionSlug: string) {
  return PRODUCTS.filter((product) => product.collections.includes(collectionSlug));
}

export function getFeaturedProducts() {
  return PRODUCTS.filter((product) => product.featured && !isComingSoon(product));
}

export function getRelatedProducts(product: Product, limit = 4) {
  return PRODUCTS.filter(
    (candidate) =>
      candidate.id !== product.id &&
      (candidate.productType === product.productType ||
        candidate.spaces.some((space) => product.spaces.includes(space))),
  ).slice(0, limit);
}
